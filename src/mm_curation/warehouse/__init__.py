"""SQL 语义层：把清洗产物组织成 ODS / DWD / DWS / ADS 四层，用 SQL 回答质量问题。

## 为什么要有这一层

漏斗跑完产出的是一堆 jsonl（cleaned / dropped）和一份判决书。
要回答「这批数据保留了多少、哪一级扔得最多、分数分布如何」，
以前要么写一次性脚本，要么翻报告——**口径散在各处，无法复用，也无法校验**。

本层把它们固化成四层模型：

| 层 | 内容 | 类比数仓 |
|---|---|---|
| ODS | 原始语料（一字不改） | 贴源层 |
| DWD | 样本事件 + 分数（清洗后、带决策） | 明细层 |
| DWS | 按数据集 / 算子 / 模态聚合 | 汇总层 |
| ADS | 指标字典定义的核心指标 | 应用层 |

## 设计约束（与项目红线一致）

- **不发明新数字**：所有指标都从已有产物算出，本层不产生新的质量判断。
- **不改 Sample / Operator 签名**，不动既有 config（新建 `configs/metrics.yaml`）。
- **可选依赖**：`duckdb` 未装时 `build()` 明确报 `unavailable`，
  不静默退化——静默退化会让「SQL 层能跑」这个结论变成假的。
- **口径进版本控制**：指标定义在 `configs/metrics.yaml`，口径变更可被校验。
"""

