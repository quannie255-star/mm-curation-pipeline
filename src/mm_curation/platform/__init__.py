"""数据平台层（S1–S6）：让「指标计算脚本」变成「有状态的数据系统」。

## 为什么单独成层，而不是往 `warehouse/` 里加

`warehouse/` 回答的是「**数据怎么组织成指标**」（语义层）；
本层回答的是「**数据系统怎么跑起来**」（作业 / 调度 / 存储 / 服务 / 运维）。
两者共享同一批语料，但抽象层次不同：一个是模型，一个是机器。

## 目录职责

| 模块 | 层 | 回答的问题 |
|---|---|---|
| `runs.py` | S1 | 这是第几次运行？跑到哪了？上次为什么失败？同批次重跑结果一样吗？ |
| `lake.py` | S2 | 数据落在哪、按什么分区、扫了多少字节？ |
| `registry.py` | S2 | 磁盘上的哪个文件是哪个数据集、事件时间从哪来？ |
| `modeling.py` | S2 | 每层各自怎么物化？维表怎么随属性变化演？ |
| `dag.py` | S3 | 什么时候算、依赖谁、失败了怎么办、怎么补数？ |
| `service.py` | S4 | 算完谁怎么用？权限在哪一层拦？ |
| `obs.py` | S5 | 怎么知道它坏了、坏了以后怎么不吵人？ |

## 两条贯穿约定

1. **`batch_date` 是「处理日期」，`event_date` 是「事件日期」**——两者不是一回事。
   本层按 `event_date` 分区（数据自己的时间），按 `batch_date` 记账（运行那一批）。
   真实 ELT 里这两个混淆是绝大多数"补数重复计数"的来源。
2. **算不出来就是算不出来**：分区缺失记 `ABSENT` 而不是 `0`（沿用 `warehouse/model.py`
   与 `quality/scorecard.py` 的同一条纪律）。
"""

